/**
 * js/sms-codegen.js
 * ─────────────────────────────────────────────────────────────────
 * Bitsy SMS — CVBasic source code generator
 *
 * Verified CVBasic SMS rules (from studying official examples):
 *
 *   Order:         CLS first, then MODE 4, then DEFINE CHAR/SPRITE
 *   BITMAP chars:  8 chars wide for DEFINE CHAR (tiles)
 *                  16 chars wide for DEFINE SPRITE (sprites are 16px wide in SMS)
 *   VPOKE:         One write per name-table cell: VPOKE $3800+(row*32+col)*2, tile_idx
 *                  CLS already zeroes attribute bytes so no second VPOKE needed
 *   SPRITE:        SPRITE n,y,x,char_index  (commas, no spaces after n)
 *   PALETTE:       PALETTE index,value  (bg palette 0-15, sprite palette 16-31)
 *   Controller:    cont1.left / cont1.right / cont1.up / cont1.down / cont1.button
 *   DATA BYTE:     One statement per line, up to 8 values each, no \ continuation
 *   RESTORE:       Per-room label + GOSUB dispatch (no seekable DATA skip)
 * ─────────────────────────────────────────────────────────────────
 */

/* ── SMS palette conversion ───────────────────────────── */
function rgbToSms(r, g, b) {
  var sr = Math.min(3, Math.round(r / 85));
  var sg = Math.min(3, Math.round(g / 85));
  var sb = Math.min(3, Math.round(b / 85));
  return (sr & 3) | ((sg & 3) << 2) | ((sb & 3) << 4);
}

/* ── pixel row helpers ────────────────────────────────── */

// 8-char BITMAP row for DEFINE CHAR (tiles are 8px wide)
function rowToCharBitmapStr(rowStr) {
  var out = "";
  for (var x = 0; x < 8; x++) out += (rowStr && rowStr[x] === "1") ? "1" : ".";
  return out;
}

// 16-char BITMAP row for DEFINE SPRITE (sprites are 16px wide in SMS Mode 4)
// Left 8px = our pixel data, right 8px = blank
function rowToSpriteBitmapStr(rowStr) {
  var out = "";
  for (var x = 0; x < 8; x++) out += (rowStr && rowStr[x] === "1") ? "1" : ".";
  out += "........";
  return out;
}

/* ── dialog sanitiser ─────────────────────────────────── */
function sanitizeDialog(txt) {
  return (txt || "...")
    .replace(/[^A-Za-z0-9 .,!?'":;()\-]/g, "?")
    .substring(0, 38);
}

/* ══════════════════════════════════════════════════════════
   MAIN GENERATOR
   ══════════════════════════════════════════════════════════ */
function generateBasCode(world) {

  /* ── palette ──────────────────────────────────────────── */
  var pal       = world.palette["0"] || [[0,0,0],[200,200,200],[255,255,255]];
  var colBg     = rgbToSms(pal[0][0], pal[0][1], pal[0][2]);
  var colTile   = rgbToSms(pal[1][0], pal[1][1], pal[1][2]);
  var colSprite = rgbToSms(pal[2][0], pal[2][1], pal[2][2]);

  /* ── tile map ─────────────────────────────────────────── */
  // Bitsy tile IDs → SMS char indices 1..N  (0 = blank/space)
  var tileIds    = Object.keys(world.tile).sort();
  var tileCharMap = {};
  tileIds.forEach(function(id, idx) { tileCharMap[id] = idx + 1; });
  var numTiles   = tileIds.length;

  /* ── NPCs ─────────────────────────────────────────────── */
  var npcIds  = Object.keys(world.sprite).filter(function(id) { return id !== "A"; }).sort();
  var numNpcs = npcIds.length;

  /* ── rooms ────────────────────────────────────────────── */
  var roomIds  = Object.keys(world.set).sort();
  var numRooms = roomIds.length;

  /* ── player start ─────────────────────────────────────── */
  var playerSprite  = world.sprite["A"];
  var playerRoom    = (playerSprite && playerSprite.set) ? playerSprite.set : "0";
  var playerX       = playerSprite ? (playerSprite.x || 4) : 4;
  var playerY       = playerSprite ? (playerSprite.y || 4) : 4;
  var playerRoomIdx = roomIds.indexOf(playerRoom);
  if (playerRoomIdx < 0) playerRoomIdx = 0;

  /* ── name-table geometry ──────────────────────────────── */
  // SMS name table: 32 cols × 28 rows, each cell = 2 bytes at $3800
  // We centre our 16×16 room: offset_col=8, offset_row=6 (fits 128px in 256×192)
  var NT_OX = 8;  // name-table column offset
  var NT_OY = 6;  // name-table row offset

  var bas = [];
  function L(s) { bas.push(s === undefined ? "" : s); }

  /* ── file header ──────────────────────────────────────── */
  L("\t' " + (world.title || "Bitsy SMS Game"));
  L("\t' Generated by Bitsy SMS");
  L();

  /* ── variable declarations ────────────────────────────── */
  L("\tDIM room_data(256)");
  L("\tDIM wall_flag(32)");
  if (numNpcs > 0) {
    L("\tDIM npc_x(" + numNpcs + ")");
    L("\tDIM npc_y(" + numNpcs + ")");
    L("\tDIM npc_room(" + numNpcs + ")");
    L("\tDIM npc_dlg(" + numNpcs + ")");
  }
  L();

  /* ── hardware init ────────────────────────────────────── */
  // IMPORTANT: CLS must come before MODE 4 (confirmed from vramcopy_sms.bas)
  L("\tCLS");
  L("\tMODE 4");
  L();

  // Set palette entries
  // Background palette: index 0 = bg colour, index 1 = tile fg colour
  // Sprite palette:     index 16 = sprite colour, index 17 = sprite bg (matches bg)
  L("\tPALETTE 0," + colBg);
  L("\tPALETTE 1," + colTile);
  L("\tPALETTE 16," + colSprite);
  L("\tPALETTE 17," + colBg);
  L();

  /* ── tile/sprite definitions ──────────────────────────── */
  // DEFINE CHAR uses 8-char BITMAP rows (tiles are 8px wide)
  // Char 0 is the blank tile we define explicitly so CLS (space char $20) shows bg colour
  // We start our tiles at char index 1
  L("\tDEFINE CHAR 1," + Math.max(numTiles, 1) + ",tile_bitmaps");
  L();

  // DEFINE SPRITE uses 16-char BITMAP rows (SMS sprites are 16px wide)
  // Sprite char 0 = player, chars 2,4,... = NPCs (each sprite uses 2 chars for 16px)
  L("\tDEFINE SPRITE 0,1,player_bitmap");
  if (numNpcs > 0) {
    L("\tDEFINE SPRITE 1," + numNpcs + ",npc_bitmaps");
  }
  L();

  /* ── game state ───────────────────────────────────────── */
  L("\tpx = " + playerX);
  L("\tpy = " + playerY);
  L("\tcur_room = " + playerRoomIdx);
  L("\tdialog_active = 0");
  L("\tdialog_idx = 0");
  L();

  /* ── NPC init ─────────────────────────────────────────── */
  if (numNpcs > 0) {
    npcIds.forEach(function(nid, i) {
      var s  = world.sprite[nid];
      var nr = roomIds.indexOf(s.set || "0");
      if (nr < 0) nr = 0;
      L("\tnpc_x(" + i + ") = " + (s.x || 0));
      L("\tnpc_y(" + i + ") = " + (s.y || 0));
      L("\tnpc_room(" + i + ") = " + nr);
      L("\tnpc_dlg(" + i + ") = " + (i + 1));
    });
    L();
  }

  /* ── startup ──────────────────────────────────────────── */
  L("\tGOSUB load_room");
  L("\tGOSUB draw_room");
  L();

  /* ══════════════════════════════════════════════════════
     MAIN LOOP
     ══════════════════════════════════════════════════════ */
  L("main_loop:");
  L("\tWAIT");
  L();

  // Dialog active — wait for button press then redraw
  L("\tIF dialog_active THEN");
  L("\t\tIF cont1.button THEN");
  L("\t\t\tdialog_active = 0");
  L("\t\t\tGOSUB draw_room");
  L("\t\tEND IF");
  L("\t\tGOTO main_loop");
  L("\tEND IF");
  L();

  // Read D-pad
  L("\tnx = px");
  L("\tny = py");
  L("\tIF cont1.left THEN nx = px - 1");
  L("\tIF cont1.right THEN nx = px + 1");
  L("\tIF cont1.up THEN ny = py - 1");
  L("\tIF cont1.down THEN ny = py + 1");
  L("\tIF nx = px AND ny = py THEN GOTO main_loop");
  L();

  // Bounds check
  L("\tIF nx < 0 OR nx > 15 THEN GOTO main_loop");
  L("\tIF ny < 0 OR ny > 15 THEN GOTO main_loop");
  L();

  // Wall check
  L("\ttile_at = room_data(ny * 16 + nx)");
  L("\tIF tile_at > 0 THEN");
  L("\t\tIF wall_flag(tile_at) THEN GOTO main_loop");
  L("\tEND IF");
  L();

  // NPC collision
  if (numNpcs > 0) {
    L("\tFOR nc = 0 TO " + (numNpcs - 1));
    L("\t\tIF npc_room(nc) = cur_room AND npc_x(nc) = nx AND npc_y(nc) = ny THEN");
    L("\t\t\tdialog_idx = npc_dlg(nc)");
    L("\t\t\tdialog_active = 1");
    L("\t\t\tGOSUB show_dialog");
    L("\t\t\tGOTO main_loop");
    L("\t\tEND IF");
    L("\tNEXT nc");
    L();
  }

  // Exit check
  L("\tGOSUB check_exits");
  L("\tIF exit_taken THEN GOTO main_loop");
  L();

  // Commit movement
  L("\tpx = nx");
  L("\tpy = ny");
  L("\tGOSUB draw_player_sprite");
  L();
  L("\tGOTO main_loop");
  L();

  /* ── check_exits ──────────────────────────────────────── */
  L("check_exits:\tPROCEDURE");
  L("\texit_taken = 0");
  var hasExit = false;
  roomIds.forEach(function(rid, ridx) {
    (world.set[rid].exits || []).forEach(function(ext) {
      hasExit = true;
      var destIdx = roomIds.indexOf(ext.dest.set);
      if (destIdx < 0) destIdx = 0;
      L("\tIF cur_room = " + ridx + " AND nx = " + ext.x + " AND ny = " + ext.y + " THEN");
      L("\t\tcur_room = " + destIdx);
      L("\t\tpx = " + ext.dest.x);
      L("\t\tpy = " + ext.dest.y);
      L("\t\tGOSUB load_room");
      L("\t\tGOSUB draw_room");
      L("\t\texit_taken = 1");
      L("\tEND IF");
    });
  });
  if (!hasExit) L("\t' no exits defined");
  L("\tEND");
  L();

  /* ── load_room dispatch ───────────────────────────────── */
  L("load_room:\tPROCEDURE");
  L("\tFOR wi = 0 TO 31");
  L("\t\twall_flag(wi) = 0");
  L("\tNEXT wi");
  roomIds.forEach(function(rid, ridx) {
    L("\tIF cur_room = " + ridx + " THEN GOSUB load_room_" + ridx);
  });
  L("\tEND");
  L();

  /* ── draw_room ────────────────────────────────────────── */
  // Write tile indices directly into SMS name table via VPOKE.
  // Name table base = $3800. Each cell = 2 bytes (tile_lo, attr_hi).
  // CLS already zeroed all attribute bytes so we only write the tile index byte.
  // Cell (col, row) on screen → VRAM address = $3800 + (row*32 + col)*2
  // Our room occupies cols NT_OX..NT_OX+15, rows NT_OY..NT_OY+15
  L("draw_room:\tPROCEDURE");
  L("\tCLS");
  L("\tFOR ry = 0 TO 15");
  L("\t\tFOR rx = 0 TO 15");
  L("\t\t\ttc = room_data(ry * 16 + rx)");
  // Compute VRAM address for this cell
  // #addr = ( (NT_OY + ry)*32 + (NT_OX + rx) ) * 2 + $3800
  L("\t\t\t#vaddr = (" + NT_OY + " + ry) * 32 + " + NT_OX + " + rx");
  L("\t\t\tVPOKE $3800 + #vaddr * 2,tc");
  L("\t\tNEXT rx");
  L("\tNEXT ry");
  L("\tGOSUB draw_player_sprite");
  if (numNpcs > 0) {
    L("\tFOR nc = 0 TO " + (numNpcs - 1));
    L("\t\tIF npc_room(nc) = cur_room THEN");
    L("\t\t\t#sx = " + (NT_OX * 8) + " + npc_x(nc) * 8");
    L("\t\t\t#sy = " + (NT_OY * 8) + " + npc_y(nc) * 8");
    L("\t\t\tSPRITE nc + 1,#sy,#sx,2");
    L("\t\tELSE");
    L("\t\t\tSPRITE nc + 1,208,0,0");
    L("\t\tEND IF");
    L("\tNEXT nc");
  }
  L("\tEND");
  L();

  /* ── draw_player_sprite ───────────────────────────────── */
  L("draw_player_sprite:\tPROCEDURE");
  L("\t#sx = " + (NT_OX * 8) + " + px * 8");
  L("\t#sy = " + (NT_OY * 8) + " + py * 8");
  L("\tSPRITE 0,#sy,#sx,0");
  L("\tEND");
  L();

  /* ── show_dialog ──────────────────────────────────────── */
  // Draw a solid bar at the bottom of the room area using PRINT AT
  // Name table row 22 = pixel row 176 (well below our 16-tile room)
  // PRINT AT 22*32 = 704
  L("show_dialog:\tPROCEDURE");
  L("\tPRINT AT 704,\"                                \"");
  L("\tPRINT AT 736,\"                                \"");
  if (numNpcs > 0) {
    npcIds.forEach(function(nid, i) {
      var dlgTxt = sanitizeDialog(world.dialog[nid] || "...");
      // Pad to fill the row
      while (dlgTxt.length < 30) dlgTxt = dlgTxt + " ";
      L("\tIF dialog_idx = " + (i + 1) + " THEN PRINT AT 705,\"" + dlgTxt + "\"");
    });
  }
  L("\tEND");
  L();

  /* ══════════════════════════════════════════════════════
     PER-ROOM LOAD SUBROUTINES
     ══════════════════════════════════════════════════════ */
  roomIds.forEach(function(rid, ridx) {
    var s       = world.set[rid];
    var wallIds = s.walls || [];

    L("load_room_" + ridx + ":\tPROCEDURE");
    L("\tRESTORE room_" + ridx + "_data");
    L("\tFOR rd = 0 TO 255");
    L("\t\tREAD BYTE room_data(rd)");
    L("\tNEXT rd");
    // Set wall flags for this room's wall tiles
    tileIds.forEach(function(tid, wi) {
      if (wallIds.indexOf(tid) >= 0) {
        L("\twall_flag(" + (wi + 1) + ") = 1");
      }
    });
    L("\tEND");
    L();

    // Room tile data: 256 bytes (16×16), 8 values per DATA BYTE line
    L("room_" + ridx + "_data:");
    var allTiles = [];
    for (var y = 0; y < 16; y++) {
      var rowStr = s.tilemap[y] || "0000000000000000";
      for (var x = 0; x < 16; x++) {
        var ch  = rowStr[x] || "0";
        var idx = (ch === "0") ? 0 : (tileCharMap[ch] !== undefined ? tileCharMap[ch] : 0);
        allTiles.push(idx);
      }
    }
    for (var di = 0; di < allTiles.length; di += 8) {
      L("\tDATA BYTE " + allTiles.slice(di, di + 8).join(","));
    }
    L();
  });

  /* ══════════════════════════════════════════════════════
     BITMAP DATA
     ══════════════════════════════════════════════════════ */

  // Tile bitmaps — 8-char rows (tiles are 8px wide)
  L("tile_bitmaps:");
  if (numTiles === 0) {
    // At least one tile required by DEFINE CHAR 1,1
    for (var y = 0; y < 8; y++) L("\tBITMAP \"........\"");
  } else {
    tileIds.forEach(function(id) {
      var src = world.imageStore.source["TIL_" + id] || [];
      for (var y = 0; y < 8; y++) L("\tBITMAP \"" + rowToCharBitmapStr(src[y]) + "\"");
    });
  }
  L();

  // Player bitmap — 16-char rows (SMS sprites are 16px wide)
  L("player_bitmap:");
  var pSrc = world.imageStore.source["SPR_A"] || [];
  for (var y = 0; y < 8; y++) L("\tBITMAP \"" + rowToSpriteBitmapStr(pSrc[y]) + "\"");
  L();

  // NPC bitmaps — 16-char rows
  if (numNpcs > 0) {
    L("npc_bitmaps:");
    npcIds.forEach(function(nid) {
      var src = world.imageStore.source["SPR_" + nid] || [];
      for (var y = 0; y < 8; y++) L("\tBITMAP \"" + rowToSpriteBitmapStr(src[y]) + "\"");
    });
    L();
  }

  return bas.join("\n");
}
